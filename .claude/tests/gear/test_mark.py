"""h19.commit-guards: commit text holds no AI mark, no Mermaid and none of the project's banned words."""
import unittest

from harness.gear.decide.arbiter import Decide
from harness.gear.detect.mark import MarkScan
from harness.utils.contracts import Event
from tests import CLAUDE_DIR


def found(message, banned=()):
    return [(f.kind, f.detail) for f in MarkScan().detect(Event("PreToolUse"), {"commit_message": message,
                                                                                 "banned": banned})]


class MarkTest(unittest.TestCase):
    def test_an_ai_mark_in_the_message_is_refused(self):
        for message in ("Fix it\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>",
                        "Fix it\n\n\U0001F916 Generated with Claude Code", "Generated by ChatGPT",
                        "Fix\n```mermaid\ngraph TD\n```"):
            with self.subTest(message=message[:20]):
                self.assertTrue(found(message))
                self.assertTrue(all(kind == "commit.ai_mark" for kind, _ in found(message)))
        for message in ("Fix the parser", "Co-Authored-By: Lan <lan@example.com>", "Read claude.md settings",
                        "Generate with care"):
            with self.subTest(message=message):
                self.assertEqual(found(message), [])
        self.assertEqual(Decide.load(CLAUDE_DIR).rules["commit.ai_mark"]["verdict"], "refuse")

    def test_a_banned_word_is_refused(self):
        self.assertEqual(found("WIP: fix the parser", ("wip",)), [("commit.banned_word", "wip")])
        self.assertEqual(found("Wipe the cache", ("wip",)), [])  # a whole word only
        self.assertEqual(found("fix", ()), [])

    def test_no_message_no_finding(self):
        self.assertEqual(MarkScan().detect(Event("PreToolUse"), {}), [])


if __name__ == "__main__":
    unittest.main()
